// Generates src/google_logo_data.ts from the SVGs in assets/google-maps-logo.
// Run with: bun run generate:logo
//
// Only the XML declaration, comments and whitespace between tags are removed;
// the logo itself (paths, colors, attributes) is left exactly as supplied,
// since Google's policies don't allow modifying it.

const ASSETS = new URL("../assets/google-maps-logo/", import.meta.url);
const OUTPUT = new URL("../src/google_logo_data.ts", import.meta.url);

const VARIANTS = {
  LIGHT_OUTLINE_SVG: "GoogleMaps_Logo_WithLightOutline.svg",
  DARK_OUTLINE_SVG: "GoogleMaps_Logo_WithDarkOutline.svg",
  GRAY_SVG: "GoogleMaps_Logo_Gray.svg",
  DARK_GRAY_SVG: "GoogleMaps_Logo_DarkGray.svg",
  WHITE_SVG: "GoogleMaps_Logo_White.svg",
};

/** Removes the XML declaration, comments and insignificant whitespace. */
export function compactSvg(svg: string): string {
  return svg
    .replace(/<\?xml[^>]*\?>/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/>\s+</g, "><")
    .replace(/\s+/g, " ")
    .trim();
}

/** Builds the contents of src/google_logo_data.ts from the asset files. */
export async function renderLogoModule(): Promise<string> {
  const lines = [
    "// Generated by scripts/generate_logo.ts from assets/google-maps-logo.",
    "// Do not edit: replace the assets and run `bun run generate:logo`.",
    "//",
    "// The Google Maps logo is a trademark of Google LLC, included only for the",
    "// attribution Google requires. It is not covered by this project's license.",
    "",
  ];
  for (const [name, file] of Object.entries(VARIANTS)) {
    const svg = await Bun.file(new URL(file, ASSETS)).text();
    lines.push(`export const ${name} =\n  ${JSON.stringify(compactSvg(svg))};`);
  }
  return `${lines.join("\n")}\n`;
}

if (import.meta.main) {
  await Bun.write(OUTPUT, await renderLogoModule());
  console.log(`Wrote ${OUTPUT.pathname}`);
}
